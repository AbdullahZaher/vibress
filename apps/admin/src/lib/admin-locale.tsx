// Reuse already certified shared dictionaries for standard UI labels;
// the publication-specific Admin vocabulary overrides shared wording.
const sharedArabicByEnglish = new Map<string, string>(
  Object.entries(enDictionary).flatMap(([key, text]) =>
    arDictionary[key] ? [[text, arDictionary[key]!]] : [],
  ),
);

function normalize(locale: string): AdminUiLocale {
  return locale.split("-")[0]?.toLowerCase() === "ar" ? "ar" : "en";
}

const Context = createContext<AdminLocaleContext | null>(null);

export function AdminLocaleProvider({
  children,
  initialLocale = "en",
}: {
  children: ReactNode;
  initialLocale?: string;
}) {
  const [locale, setLocale] = useState<AdminUiLocale>(normalize(initialLocale));
  const [userId, setUserIdState] = useState<string | null>(null);

  const setUserId = useCallback((value: string | null) => {
    setUserIdState(value);
  }, []);

  const setUiLocale = useCallback((value: string) => {
    const nextLocale = normalize(value);
    setLocale(nextLocale);
    if (userId && typeof window !== "undefined") {
      try {
        window.localStorage.setItem(`vibress-admin-ui-locale:${userId}`, nextLocale);
      } catch {
        // Keep the in-memory preference when browser storage is unavailable.
      }
    }
  }, [userId]);

  const refresh = useCallback(async () => {
    // The staff interface language is a user preference, independent from the
    // publication's primary language. Fall back to the publication only when
    // this staff account has not selected an interface language.
    if (userId && typeof window !== "undefined") {
      try {
        const saved = window.localStorage.getItem(`vibress-admin-ui-locale:${userId}`);
        if (saved === "ar" || saved === "en") {
          setLocale(saved);
          return;
        }
      } catch {
        // Continue with the publication default if storage is unavailable.
      }
    }

    try {
      const config = await getPublicationLocaleContextApi();
      setLocale(normalize(config.primaryLocale));
      return;
    } catch {
      // Anonymous login, first-run setup, or staff without settings.read.
    }
    try {
      const response = await fetch("/api/content/v1/site", {
        credentials: "same-origin", cache: "no-store",
      });
      if (!response.ok) return;
      const json: unknown = await response.json();
      if (json && typeof json === "object" && "site" in json &&
          json.site && typeof json.site === "object" &&
          "locale" in json.site && typeof json.site.locale === "string") {
        setLocale(normalize(json.site.locale));
      }
    } catch {
      // Setup or API outage: retain the current displayed language.
    }
  }, [userId]);

  useEffect(() => {
    void refresh();
    const onUpdate = () => { void refresh(); };
    window.addEventListener("vibress:locales-updated", onUpdate);
    return () => window.removeEventListener("vibress:locales-updated", onUpdate);
  }, [refresh]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const tr = useCallback((english: string) =>
    locale === "ar"
      ? translations[english] || sharedArabicByEnglish.get(english) || english
      : english, [locale]);

  const formatDate = useCallback((date: Date | string | number, options?: Intl.DateTimeFormatOptions) => {
    return i18nFormatDate(date, locale === "ar" ? "ar-SA" : "en-US", options);
  }, [locale]);

  const formatNumber = useCallback((num: number, options?: Intl.NumberFormatOptions) => {
    return i18nFormatNumber(num, locale === "ar" ? "ar-SA" : "en-US", options);
  }, [locale]);

  const formatRelativeTime = useCallback((date: Date | string | number, baseDate?: Date | string) => {
    return i18nFormatRelativeTime(date, locale === "ar" ? "ar-SA" : "en-US", baseDate);
  }, [locale]);

  const value = useMemo(() => ({
    locale, setUiLocale, setUserId, refresh, tr, formatDate, formatNumber, formatRelativeTime,
  }), [locale, setUiLocale, setUserId, refresh, tr, formatDate, formatNumber, formatRelativeTime]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

const defaultAdminLocaleContext: AdminLocaleContext = {
  locale: "en",
  setUiLocale: () => {},
  setUserId: () => {},
  refresh: async () => {},
  tr: (english: string) => english,
  formatDate: (date: Date | string | number, options?: Intl.DateTimeFormatOptions) =>
    i18nFormatDate(date, "en-US", options),
  formatNumber: (num: number, options?: Intl.NumberFormatOptions) =>
    i18nFormatNumber(num, "en-US", options),
  formatRelativeTime: (date: Date | string | number, baseDate?: Date | string) =>
    i18nFormatRelativeTime(date, "en-US", baseDate),
};

export function useAdminLocale(): AdminLocaleContext {
  const context = useContext(Context);
  return context ?? defaultAdminLocaleContext;
}
